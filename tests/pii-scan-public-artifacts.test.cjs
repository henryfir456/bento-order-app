const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { test } = require('node:test');

const scanner = path.join(__dirname, '../scripts/pii-scan-public-artifacts.mjs');
const diffFor = (line) => [
  'diff --git a/fixture.js b/fixture.js',
  '--- a/fixture.js',
  '+++ b/fixture.js',
  `+${line}`,
  ''
].join('\n');
const diffForFile = (file, line) => [
  `diff --git a/${file} b/${file}`,
  `--- a/${file}`,
  `+++ b/${file}`,
  `+${line}`,
  ''
].join('\n');

test('PII scan blocks a numeric employee value generated by a repeated-character expression', () => {
  const quote = String.fromCharCode(39);
  const generatedExpression = `${quote}5${quote}.repeat(6)`;
  const result = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffFor(`const employeeId = ${generatedExpression};`)
  });
  assert.equal(result.status, 1, JSON.stringify({ stdout: result.stdout, stderr: result.stderr }));
  assert.match(result.stderr, /numeric identifier generated by repeat expression/);
  assert.doesNotMatch(result.stderr, /[0-9]{5,}/);
});

test('PII scan allows a clearly synthetic account mapping expression', () => {
  const result = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffFor("const employeeId = 'SYNTHETIC-PROTECTED-EMPLOYEE';")
  });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /PII_SCAN PASS/);
});

test('PII scan allows only the typed public commit SHA in the formal deployment baseline', () => {
  const publicCommitSha = 'a'.repeat(40);
  const result = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffForFile('worker-poc/scripts/detect-formal-drift.mjs', `  sourceSha: '${publicCommitSha}'`)
  });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /PII_SCAN PASS/);

  const generatedId = ['555', '555'].join('');
  const unrelated = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffForFile('worker-poc/scripts/detect-formal-drift.mjs', `  employeeId: ${generatedId}`)
  });
  assert.equal(unrelated.status, 1);
  assert.match(unrelated.stderr, /numeric employee or phone pattern/);
});

test('PII scan allows only typed UAT resource identifiers and still blocks nearby numeric identities', () => {
  const uatName = ['bento-order-app-uat-', '2026', '1019'].join('');
  const uatId = 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa';
  const allowedConfig = [
    `  "name": "${uatName}",`,
    `  "database_name": "${uatName}",`,
    `  "database_id": "${uatId}",`
  ].join('\n');
  const allowed = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: [
      'diff --git a/worker-poc/wrangler.uat.jsonc b/worker-poc/wrangler.uat.jsonc',
      '--- a/worker-poc/wrangler.uat.jsonc',
      '+++ b/worker-poc/wrangler.uat.jsonc',
      ...allowedConfig.split('\n').map((line) => `+${line}`),
      ''
    ].join('\n')
  });
  assert.equal(allowed.status, 0, allowed.stderr);

  const unrelatedNumericValue = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffForFile('worker-poc/wrangler.uat.jsonc', `  "line_user_id": "${['1234', '567', '89'].join('')}",`)
  });
  assert.equal(unrelatedNumericValue.status, 1, unrelatedNumericValue.stdout);
  assert.match(unrelatedNumericValue.stderr, /numeric employee or phone pattern/);
});


test('retrospective accepts typed public Git SHA and Actions run ID, not untyped numbers', () => {
  const file = 'docs/retrospectives/2026-10-21-cloud-local-deployment-routing.md';
  const sha = 'a3b4c5d6e7f8a9b0c1d2e3f4a5b6c7d8e9f01234';
  const run = ['3953', '8944', '352'].join('');
  const accepted = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: [
      'diff --git a/' + file + ' b/' + file,
      '--- a/' + file,
      '+++ b/' + file,
      '+- Verification on source commit ' + String.fromCharCode(96) + sha + String.fromCharCode(96),
      '+- Earlier head ' + String.fromCharCode(96) + sha + String.fromCharCode(96),
      '+- GitHub Actions run ' + String.fromCharCode(96) + run + String.fromCharCode(96) + ' had a test failure',
      ''
    ].join('\n')
  });
  assert.equal(accepted.status, 0, accepted.stderr);
  for (const [pathName, line] of [
    [file, 'Employee ID ' + ['1234', '5678'].join('') + ', head ' + String.fromCharCode(96) + sha + String.fromCharCode(96)],
    [file, 'GitHub Actions run ' + String.fromCharCode(96) + run + String.fromCharCode(96) + ' phone ' + ['0912', '345', '678'].join('')],
    ['docs/random.md', 'head ' + String.fromCharCode(96) + sha + String.fromCharCode(96)],
    [file, 'untyped run ' + run]
  ]) {
    const actual = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
      encoding: 'utf8', input: diffForFile(pathName, line)
    });
    assert.equal(actual.status, 1, pathName + ' ' + actual.stderr);
    assert.match(actual.stderr, /numeric employee or phone pattern/);
  }
});
