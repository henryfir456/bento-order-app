const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const { test } = require('node:test');

const scanner = path.join(__dirname, '../scripts/pii-scan-public-artifacts.mjs');
const diffFor = (line) => [
  'diff --git a/fixture.js b/fixture.js',
  '--- a/fixture.js',
  '+++ b/fixture.js',
  `+${line}`,
  ''
].join('\n');

test('PII scan blocks a numeric employee value generated by a repeated-character expression', () => {
  const quote = String.fromCharCode(39);
  const generatedExpression = `${quote}5${quote}.repeat(6)`;
  const result = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffFor(`const employeeId = ${generatedExpression};`)
  });
  assert.equal(result.status, 1, JSON.stringify({ stdout: result.stdout, stderr: result.stderr }));
  assert.match(result.stderr, /numeric identifier generated by repeat expression/);
  assert.doesNotMatch(result.stderr, /[0-9]{5,}/);
});

test('PII scan allows a clearly synthetic account mapping expression', () => {
  const result = spawnSync(process.execPath, [scanner, '--diff-stdin'], {
    encoding: 'utf8',
    input: diffFor("const employeeId = 'SYNTHETIC-PROTECTED-EMPLOYEE';")
  });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /PII_SCAN PASS/);
});
